/**
 * Returns exact requested number of questions for any full mock test.
 * Multi-subject guaranteed and deterministically seeded by test identifier.
 */
export function getFullMockQuestions(count: number = 100, testIdOrTitle: string = ""): DrillQuestion[] {
  const totalAvailable = FULL_MOCK_105_QUESTIONS.length;
  const targetCount = Math.min(Math.max(count, 10), totalAvailable);

  // Compute a simple hash from testIdOrTitle to vary starting order between different tests
  let seed = 0;
  for (let i = 0; i < testIdOrTitle.length; i++) {
    seed = (seed * 31 + testIdOrTitle.charCodeAt(i)) % totalAvailable;
  }

  // Rotate list by seed so Mock 1, Mock 2, Mock 3 have differing questions or order
  const rotated = [
    ...FULL_MOCK_105_QUESTIONS.slice(seed),
    ...FULL_MOCK_105_QUESTIONS.slice(0, seed),
  ];

  return rotated.slice(0, targetCount);
}
