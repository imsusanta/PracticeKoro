export function getMockTestPreset(testId: string): MockTestPreset | null {
  if (PRESET_MOCK_CATALOG[testId]) {
    return PRESET_MOCK_CATALOG[testId];
  }
  const cleanId = testId.toLowerCase().trim();
  for (const [key, preset] of Object.entries(PRESET_MOCK_CATALOG)) {
    if (cleanId === key || cleanId.startsWith(key)) {
      return preset;
    }
  }
  return null;
}

